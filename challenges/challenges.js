// دالة لإنشاء أسئلة إضافية حسب الحاجة
function generateAdditionalQuestions(count) {
    const additionalQuestions = [];
    
    const subjects = ['الإسلامية', 'العربي', 'الانجليزي', 'الرياضيات', 'الاجتماعيات', 'الكيمياء', 'الفيزياء', 'الأحياء', 'الحاسوب', 'الفنية', 'الرياضة'];
    const grades = Array.from({length: 12}, (_, i) => `الصف ${i + 1}`);
    const types = ['Challenger', 'Adventurer', 'Hacker'];
    
    for (let i = 0; i < count; i++) {
        const type = types[Math.floor(Math.random() * types.length)];
        const grade = grades[Math.floor(Math.random() * grades.length)];
        const subject = subjects[Math.floor(Math.random() * subjects.length)];
        
        additionalQuestions.push({
            id: window.defaultChallenges.length + i + 1,
            type: type,
            grade: grade,
            subject: subject,
            question: `سؤال ${i + 1} في مادة ${subject} للمرحلة ${grade}`,
            format: Math.random() > 0.5 ? 'فراغ' : 'خيار من متعدد',
            correctAnswer: 'إجابة صحيحة',
            options: ['خيار ١', 'خيار ٢', 'خيار ٣', 'خيار ٤'],
            pdf: null,
            points: type === 'Challenger' ? 5 : type === 'Adventurer' ? 8 : 12,
            image: null
        });
    }
    
    return additionalQuestions;
}

// إضافة أسئلة إضافية إذا لزم الأمر
if (window.defaultChallenges.length < 50) {
    const needed = 50 - window.defaultChallenges.length;
    const extraQuestions = generateAdditionalQuestions(needed);
    window.defaultChallenges.push(...extraQuestions);
}


